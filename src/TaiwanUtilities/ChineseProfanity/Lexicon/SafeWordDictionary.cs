    private static Trie Build()
    {
        var trie = new Trie();
        foreach (var word in s_safeWords)
        {
            trie.Add(word);
        }
        return trie;
    }

    /// <summary>
    /// 從位置 index 開始嘗試最大匹配安全詞。
    /// 回傳匹配到的安全詞長度，0 表示沒有匹配。
    /// </summary>
    internal static int TryMatchSafeWord(ReadOnlySpan<char> text, int index)
    {
        return s_trie.Value.LongestMatch(text, index);
    }
