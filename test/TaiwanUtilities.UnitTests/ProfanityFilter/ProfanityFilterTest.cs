namespace TaiwanUtilities.UnitTests;

using Xunit;

public class ProfanityFilterTest
{
    [Fact]
    public void 檢查是否帶有髒話()
    {
        // 測試文章
        var testArticle =
            """
                欠人姦是不是
                靠你媽北
                靠你媽的北
                靠北三小
            
